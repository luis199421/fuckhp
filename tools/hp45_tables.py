#!/usr/bin/env python3
"""HP45 (51645A) nozzle map: single source of truth.

Every one of the 300 nozzles sits at the crossing of one *primitive* line
(P1..P14, the power line) and one *address* line (A1..A22, the gate line).
To fire nozzle n you put ~12 V on its address line and pulse its primitive.

The raw tables below are the community reverse-engineered map published by
Yvo de Haas (Ytec3D) in https://github.com/yvodehaas/HP45-standalone-V4
(NewNozzleTable.ino, GPL-3.0).  Indexes are 0-based: primitive 0 == "P1".

That published address table contains 7 entries that put two nozzles on the
same (primitive, address) crossing, which is physically impossible (they would
be the same heater resistor).  The table is otherwise exactly periodic with a
period of 44 nozzles, and replacing those 7 entries with the periodic value
turns the map into a perfect one-to-one mapping.  CORRECTIONS records them so
the change is auditable.  `python3 tools/hp45_tables.py --check` verifies it.

Nozzle parity == nozzle row: even nozzles are in one column of holes, odd
nozzles in the other column, ~4.05 mm apart (ROW_GAP_UM).  Consecutive
nozzles are 1/600 inch apart vertically, so one pass covers 300 rows = 12.7 mm.

Run with --emit-c to regenerate firmware/src/hp45_map.c.
"""
import sys
from collections import Counter
from pathlib import Path

ROWS = 300
PRIMITIVES = 14
ADDRESSES = 22
ROW_GAP_UM = 4050  # distance between the odd and even nozzle columns

RAW_ADDRESS = [
    0, 8, 15, 1, 8, 16, 1, 9, 16, 2, 9, 17, 2, 10, 17, 3, 10, 18, 3, 11,
    18, 4, 11, 19, 4, 12, 19, 5, 12, 20, 5, 13, 20, 6, 13, 21, 16, 14, 21, 7,
    14, 0, 7, 12, 0, 8, 15, 1, 8, 16, 1, 9, 16, 2, 9, 17, 2, 10, 17, 3,
    10, 18, 3, 11, 18, 4, 11, 19, 4, 12, 19, 5, 12, 20, 5, 13, 20, 6, 13, 21,
    6, 14, 21, 7, 14, 0, 7, 15, 0, 8, 15, 1, 8, 16, 1, 9, 16, 2, 9, 17,
    2, 10, 17, 3, 10, 18, 3, 11, 18, 4, 11, 19, 4, 12, 19, 5, 12, 20, 5, 13,
    20, 6, 13, 21, 6, 14, 21, 7, 14, 0, 7, 15, 0, 8, 15, 1, 8, 16, 1, 9,
    16, 2, 9, 17, 2, 10, 17, 3, 10, 18, 3, 11, 18, 4, 11, 19, 4, 12, 19, 5,
    12, 20, 5, 13, 20, 6, 13, 21, 6, 14, 0, 7, 15, 0, 7, 15, 0, 8, 15, 1,
    8, 16, 1, 9, 18, 2, 9, 17, 2, 10, 17, 3, 10, 18, 3, 11, 18, 4, 11, 19,
    4, 12, 19, 5, 12, 20, 5, 13, 20, 6, 13, 21, 6, 14, 21, 7, 14, 0, 7, 15,
    0, 8, 15, 1, 8, 16, 1, 9, 16, 2, 9, 17, 2, 10, 17, 3, 10, 18, 3, 11,
    18, 4, 11, 21, 4, 12, 19, 5, 12, 20, 5, 13, 20, 6, 13, 21, 6, 14, 21, 7,
    14, 0, 7, 15, 0, 8, 15, 1, 8, 16, 1, 9, 16, 2, 9, 17, 2, 10, 17, 3,
    10, 18, 3, 11, 18, 4, 11, 19, 4, 12, 19, 5, 12, 20, 5, 13, 20, 6, 13, 20,
]

# primitive = 2*(n // 44-ish block) + parity; stored explicitly to match source
RAW_PRIMITIVE = (
    [0, 1] * 20 + [2, 3] * 22 + [4, 5] * 22 + [6, 7] * 22 +
    [8, 9] * 22 + [10, 11] * 22 + [12, 13] * 20
)

# nozzle index -> (published value, corrected value)
CORRECTIONS = {36: (16, 6), 43: (12, 15), 170: (0, 21), 172: (15, 14),
               184: (18, 16), 243: (21, 19), 299: (20, 21)}


def corrected_address():
    a = list(RAW_ADDRESS)
    for n, (old, new) in CORRECTIONS.items():
        assert a[n] == old, (n, a[n], old)
        a[n] = new
    return a


ADDRESS = corrected_address()
PRIMITIVE = list(RAW_PRIMITIVE)


def check():
    assert len(ADDRESS) == ROWS and len(PRIMITIVE) == ROWS
    pairs = Counter(zip(PRIMITIVE, ADDRESS))
    dups = [k for k, v in pairs.items() if v > 1]
    assert not dups, dups
    assert all(0 <= a < ADDRESSES for a in ADDRESS)
    assert all(0 <= p < PRIMITIVES for p in PRIMITIVE)
    # row parity == primitive parity (each primitive serves one nozzle column)
    assert all(PRIMITIVE[n] % 2 == n % 2 for n in range(ROWS))
    # corrections are exactly the values the 44-periodic pattern predicts
    for n in CORRECTIONS:
        same_phase = [RAW_ADDRESS[m] for m in range(n % 44, ROWS, 44) if m != n]
        assert Counter(same_phase).most_common(1)[0][0] == ADDRESS[n], n
    return True


def emit_c():
    def rows(vals):
        out = []
        for i in range(0, len(vals), 20):
            out.append("    " + ", ".join(f"{v:2d}" for v in vals[i:i + 20]) + ",")
        return "\n".join(out)
    return f"""// GENERATED by tools/hp45_tables.py -- do not edit by hand.
// HP45 nozzle -> (address, primitive) map. 0-based: address 0 == A1, primitive 0 == P1.
// Source: Yvo de Haas, HP45-standalone-V4 (GPL-3.0), with {len(CORRECTIONS)} corrections, see the script.
#include "hp45_map.h"

const uint8_t hp45_nozzle_address[HP45_NOZZLES] = {{
{rows(ADDRESS)}
}};

const uint8_t hp45_nozzle_primitive[HP45_NOZZLES] = {{
{rows(PRIMITIVE)}
}};
"""


if __name__ == "__main__":
    check()
    if "--emit-c" in sys.argv:
        out = Path(__file__).resolve().parent.parent / "firmware" / "src" / "hp45_map.c"
        out.write_text(emit_c())
        print("wrote", out)
    else:
        print("HP45 map OK: 300 nozzles, one-to-one over 14 primitives x 22 addresses")
