#!/usr/bin/env python3
"""Generate firmware/src/params_table.h from host/freejet/params.py."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "host"))
from freejet.params import PARAMS  # noqa: E402


def render() -> str:
    lines = ["// GENERATED by tools/gen_params.py from host/freejet/params.py -- do not edit.",
             "#pragma once", "", "// X(id, NAME, default, min, max)", "#define FJ_PARAMS(X) \\"]
    for p in PARAMS:
        lines.append(f"    X({p.id:3d}, {p.name.upper():22s}, {p.default:8d}, {p.min:8d}, {p.max:8d}) \\")
    lines.append("")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out = ROOT / "firmware" / "src" / "params_table.h"
    out.write_text(render())
    print("wrote", out)
